"""PharmD levels -> TradingView Pine Script indicator.
    python tv_levels.py                 # newest weekly + any daily plans dated after it
    python tv_levels.py plans/weekly-2026-11-01.json plans/plan-2026-11-02.json
Writes tradingview/pharmd_levels.pine: paste it into TradingView's Pine Editor and "Add to chart".
One script for both instruments: it draws the ES block on ES/MES charts and the NQ block on NQ/MNQ charts."""
import json, glob, os, sys

OUT = "tradingview/pharmd_levels.pine"
ROOTS = {"ES": ("ES", "MES"), "NQ": ("NQ", "MNQ")}
# weekly list lines: plain / starred / LAAF-LBAF tags; daily brief kinds: up / down / pivot / ref
COL = {"w": "color.gray", "w*": "color.orange", "laaf": "color.red", "lbaf": "color.lime", "zone": "color.blue",
       "ref": "color.purple", "up": "color.red", "down": "color.lime", "pivot": "color.yellow"}


def latest_plans():
    weekly = sorted(glob.glob("plans/weekly-*.json"))[-1]
    wk = json.load(open(weekly))["week_of"]
    daily = [p for p in sorted(glob.glob("plans/plan-*.json")) if p[len("plans/plan-"):-5] > wk]
    return [weekly] + daily


def pstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(v):
    return f"{float(v):g}"


def weekly_rows(p, sym):
    rows = []
    for l in p["levels"].get(sym, []):
        lo, hi = l["zone"]
        if not all(isinstance(v, (int, float)) for v in (lo, hi)): continue
        tag = l.get("tag", "")
        c = "laaf" if "laaf" in tag else "lbaf" if "lbaf" in tag else "w*" if l.get("strong") else "w"
        rows.append(("weekly", lo, hi, "W " + l["line"], c, bool(l.get("strong"))))
    for z in p["zones"].get(sym, []):
        lo, hi = z["zone"]
        if not all(isinstance(v, (int, float)) for v in (lo, hi)): continue
        c = "zone" if z.get("type") == "zone" else "ref"
        rows.append(("zones", lo, hi, f"W {num(lo)}" + (f"-{num(hi)}" if hi != lo else "") + f" {z['label']}", c, False))
    return rows


def daily_rows(p, sym):
    rows, tag = [], "D" + p["date"][5:].replace("-", "/")
    for b in p.get("brief", []):
        if b["instrument"] != sym: continue
        for l in b["levels"]:
            ps = [v for v in l["p"] if isinstance(v, (int, float))]
            if not ps: continue
            lo, hi = min(ps), max(ps)
            txt = f"{tag} {num(lo)}" + (f"-{num(hi)}" if hi != lo else "") + (f"{'*' if l.get('strong') else ''} {l['label']}" if l["label"] or l.get("strong") else "")
            rows.append(("daily", lo, hi, txt.rstrip(), l["kind"] if l["kind"] in COL else "ref", bool(l.get("strong"))))
    return rows


def build(paths):
    plans = [json.load(open(x)) for x in paths]
    names = [("week of " + p["week_of"]) if p.get("type") == "weekly" else p["date"] for p in plans]
    contracts = {}
    for p in plans:
        contracts.update(p.get("contract") or {})
    out = [
        "//@version=6",
        f"// PharmD levels, generated by tv_levels.py from: {', '.join(os.path.basename(x) for x in paths)}",
        f"// Contracts: {', '.join(f'{k} {v}' for k, v in sorted(contracts.items())) or 'see plan'}."
        " Use the front contract or an UNADJUSTED continuous chart (ES1!/NQ1!); back-adjusted charts shift prices.",
        f'indicator({pstr("PharmD levels · " + " + ".join(names))}, overlay=true, max_boxes_count=500, max_lines_count=500, max_labels_count=500)',
        "",
        'showWeekly = input.bool(true, "Weekly levels")',
        'showZones  = input.bool(true, "Weekly zones / refs")',
        'showDaily  = input.bool(true, "Daily plan levels")',
        'showLabels = input.bool(true, "Labels")',
        'barsBack   = input.int(300, "Start N bars back", minval=1, maxval=4900)',
        "",
        "lvl(float lo, float hi, string txt, color col, bool strong) =>",
        "    left = math.max(0, bar_index - barsBack)",
        "    if lo == hi",
        "        line.new(left, lo, bar_index, lo, extend=extend.right, color=col, width=strong ? 2 : 1, style=line.style_dashed)",
        "    if lo != hi",
        "        box.new(left, hi, bar_index, lo, border_color=col, border_width=strong ? 2 : 1, bgcolor=color.new(col, strong ? 75 : 88), extend=extend.right)",
        "    if showLabels",
        "        label.new(bar_index + 3, (lo + hi) / 2, txt, style=label.style_label_left, color=color.new(color.black, 100), textcolor=col, size=size.small)",
        "    0",
        "",
        "var bool drawn = false",
        "if barstate.islast and not drawn",
        "    drawn := true",
    ]
    for sym, roots in ROOTS.items():
        rows = []
        for p in plans:
            rows += weekly_rows(p, sym) if p.get("type") == "weekly" else daily_rows(p, sym)
        if not rows: continue
        cond = " or ".join(f'syminfo.root == "{r}"' for r in roots)
        out.append(f"    if {cond}")
        for grp, lo, hi, txt, c, strong in rows:
            show = {"weekly": "showWeekly", "zones": "showZones", "daily": "showDaily"}[grp]
            out.append(f"        if {show}")
            out.append(f"            lvl({num(lo)}, {num(hi)}, {pstr(txt)}, {COL[c]}, {'true' if strong else 'false'})")
    return "\n".join(out) + "\n", sum(1 for l in out if l.strip().startswith("lvl("))


if __name__ == "__main__":
    paths = sys.argv[1:] or latest_plans()
    src, n = build(paths)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(src)
    print(f"{OUT}: {n} levels from {', '.join(paths)}")
